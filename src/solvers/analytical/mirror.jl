"""
    MagneticMirror{T} <: AbstractMagneticField

Magnetic field from a magnetic mirror generated by two coaxial circular coils.

# Fields
- `distance::T`: Distance between coil centers [m].
- `radius::T`: Radius of each coil [m].
- `current::T`: Current times windings in each coil [A].
- `center::SVector{3, T}`: Midpoint between coils [m].
- `normal::SVector{3, T}`: Symmetry axis unit vector.
"""
struct MagneticMirror{T} <: AbstractMagneticField
    distance::T
    radius::T
    current::T
    center::SVector{3, T}
    normal::SVector{3, T}

    function MagneticMirror(
            distance, radius, current;
            center = SA[0.0, 0.0, 0.0],
            normal = SA[0.0, 0.0, 1.0]
        )
        T = promote_type(
            typeof(distance), typeof(radius), typeof(current),
            eltype(center), eltype(normal)
        )
        T_float = T <: AbstractFloat ? T : Float64
        n_hat = normalize(SVector{3, T_float}(normal))
        return new{T_float}(
            T_float(distance), T_float(radius), T_float(current),
            SVector{3, T_float}(center), n_hat
        )
    end
end

@inline function (field::MagneticMirror)(r)
    (; distance, radius, current, center, normal) = field
    c1 = center - 0.5 * distance * normal
    c2 = center + 0.5 * distance * normal
    cl1 = CurrentLoop(radius, current, c1, normal)
    cl2 = CurrentLoop(radius, current, c2, normal)
    return getB_loop(r, cl1) + getB_loop(r, cl2)
end

"""
    getB_mirror(x, y, z, distance, a, I1) -> SVector{3}
    getB_mirror(r, distance, a, I1; center=[0,0,0], normal=[0,0,1]) -> SVector{3}

Get magnetic field from a magnetic mirror generated from two coils.
"""
@inline function getB_mirror(x, y, z, distance, a, I1)
    return getB_mirror(SVector(x, y, z), distance, a, I1)
end

@inline function getB_mirror(
        r, distance, a, I1; center = SVector(0.0, 0.0, 0.0),
        normal = SVector(0.0, 0.0, 1.0)
    )
    return MagneticMirror(distance, a, I1; center, normal)(r)
end

"""
    MagneticBottle{T} <: AbstractMagneticField

Magnetic field from a magnetic bottle configuration (two mirror coils plus a central coil).

# Fields
- `distance::T`: Distance between mirror coils [m].
- `radius_side::T`: Radius of side coils [m].
- `radius_center::T`: Radius of central coil [m].
- `current_side::T`: Current in side coils [A].
- `current_center::T`: Current in central coil [A].
- `center::SVector{3, T}`: Center of symmetry [m].
- `normal::SVector{3, T}`: Symmetry axis unit vector.
"""
struct MagneticBottle{T} <: AbstractMagneticField
    distance::T
    radius_side::T
    radius_center::T
    current_side::T
    current_center::T
    center::SVector{3, T}
    normal::SVector{3, T}

    function MagneticBottle(
            distance, radius_side, radius_center, current_side, current_center;
            center = SA[0.0, 0.0, 0.0],
            normal = SA[0.0, 0.0, 1.0]
        )
        T = promote_type(
            typeof(distance), typeof(radius_side), typeof(radius_center),
            typeof(current_side), typeof(current_center),
            eltype(center), eltype(normal)
        )
        T_float = T <: AbstractFloat ? T : Float64
        n_hat = normalize(SVector{3, T_float}(normal))
        return new{T_float}(
            T_float(distance), T_float(radius_side), T_float(radius_center),
            T_float(current_side), T_float(current_center),
            SVector{3, T_float}(center), n_hat
        )
    end
end

@inline function (field::MagneticBottle)(r)
    (; distance, radius_side, radius_center, current_side, current_center, center, normal) = field
    B_mirror = MagneticMirror(distance, radius_side, current_side; center, normal)(r)
    cl3 = CurrentLoop(radius_center, current_center, center, normal)
    return B_mirror + getB_loop(r, cl3)
end

"""
    getB_bottle(x, y, z, distance, a, b, I1, I2) -> SVector{3}
    getB_bottle(r, distance, a, b, I1, I2; center=[0,0,0], normal=[0,0,1]) -> SVector{3}

Get magnetic field from a magnetic bottle.
"""
@inline function getB_bottle(
        x, y, z, distance, a, b, I1, I2;
        center = SVector(0.0, 0.0, 0.0),
        normal = SVector(0.0, 0.0, 1.0)
    )
    return getB_bottle(SVector(x, y, z), distance, a, b, I1, I2; center, normal)
end

@inline function getB_bottle(
        r, distance, a, b, I1, I2; center = SVector(0.0, 0.0, 0.0),
        normal = SVector(0.0, 0.0, 1.0)
    )
    return MagneticBottle(distance, a, b, I1, I2; center, normal)(r)
end
