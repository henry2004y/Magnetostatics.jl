"""
    TokamakCoils{T} <: AbstractMagneticField

Tokamak magnetic field generated by toroidal field coils and a central plasma current ring.

# Fields
- `a::T`: Characteristic coil radius parameter [m] (coil radius is 2a).
- `b::T`: Radius of central region [m].
- `ICoils::T`: Current times windings in toroidal coils [A].
- `IPlasma::T`: Total plasma current [A].
- `n_coils::Int`: Number of toroidal field coils (default: 16).
"""
struct TokamakCoils{T} <: AbstractMagneticField
    a::T
    b::T
    ICoils::T
    IPlasma::T
    n_coils::Int

    function TokamakCoils(a, b, ICoils, IPlasma; n_coils = 16)
        T = promote_type(typeof(a), typeof(b), typeof(ICoils), typeof(IPlasma))
        T_float = T <: AbstractFloat ? T : Float64
        return new{T_float}(
            T_float(a), T_float(b), T_float(ICoils), T_float(IPlasma), Int(n_coils)
        )
    end
end

@inline function (field::TokamakCoils{T})(r) where {T}
    x, y, z = r[1], r[2], r[3]
    (; a, b, ICoils, IPlasma, n_coils) = field
    R_coil = a * 2

    Bx, By, Bz = zero(T), zero(T), zero(T)

    for i in 0:(n_coils - 1)
        θ = π / n_coils + i * 2π / n_coils
        R_major = b + R_coil
        center = SVector(R_major * cos(θ), R_major * sin(θ), zero(T))
        normal = SVector(-sin(θ), cos(θ), zero(T))

        cl = CurrentLoop(R_coil, ICoils, center, normal)
        B_coil = getB_loop(r, cl)

        Bx += B_coil[1]
        By += B_coil[2]
        Bz += B_coil[3]
    end

    σ = R_coil / 3
    ϕ = atan(y, x)
    R_p = R_coil + b
    dist_val = √(z^2 + (x - R_p * cos(ϕ))^2 + (y - R_p * sin(ϕ))^2)

    if dist_val > 1.0e-4
        I2_r_plasma = IPlasma * erf(dist_val / (σ * √2))
        cl_plasma = CurrentLoop(
            R_p, I2_r_plasma,
            SVector(zero(T), zero(T), zero(T)), SVector(zero(T), zero(T), one(T))
        )
        B_plasma = getB_loop(r, cl_plasma)

        Bx += B_plasma[1]
        By += B_plasma[2]
        Bz += B_plasma[3]
    end

    return SVector{3, T}(Bx, By, Bz)
end

"""
    getB_tokamak_coil(x, y, z, a, b, ICoils, IPlasma) -> SVector{3}
    getB_tokamak_coil(r, a, b, ICoils, IPlasma) -> SVector{3}

Get the magnetic field from a Tokamak topology consisting of 16 coils.
"""
@inline function getB_tokamak_coil(x, y, z, a, b, ICoils, IPlasma)
    return getB_tokamak_coil(SVector(x, y, z), a, b, ICoils, IPlasma)
end

@inline function getB_tokamak_coil(r, a, b, ICoils, IPlasma)
    return TokamakCoils(a, b, ICoils, IPlasma)(r)
end

"""
    TokamakProfile{F, T} <: AbstractMagneticField

Tokamak magnetic field distribution reconstructed from a safety factor q-profile.

# Fields
- `q_profile::F`: Function of normalized radius `r/a` returning `q`.
- `a::T`: Minor radius [m].
- `R₀::T`: Major radius [m].
- `Bζ0::T`: Toroidal magnetic field on axis [T].
"""
struct TokamakProfile{F, T} <: AbstractMagneticField
    q_profile::F
    a::T
    R₀::T
    Bζ0::T

    function TokamakProfile(q_profile::F, a, R₀, Bζ0) where {F}
        T = promote_type(typeof(a), typeof(R₀), typeof(Bζ0))
        T_float = T <: AbstractFloat ? T : Float64
        return new{F, T_float}(q_profile, T_float(a), T_float(R₀), T_float(Bζ0))
    end
end

@inline function (field::TokamakProfile{F, T})(pos) where {F, T}
    x, y, z = pos[1], pos[2], pos[3]
    (; q_profile, a, R₀, Bζ0) = field
    R = √(x^2 + y^2)
    r = √((R - R₀)^2 + z^2)
    r > a && throw(OverflowError("out of vacuum vessel"))
    θ = atan(z, R - R₀)
    Bζ = Bζ0 * R₀ / R
    Bθ = r * Bζ / R₀ / q_profile(r / a)
    ζ = atan(y, x)
    sinζ, cosζ = sincos(ζ)
    sinθ, cosθ = sincos(θ)

    Bx = -Bζ * sinζ - Bθ * sinθ * cosζ
    By = Bζ * cosζ - Bθ * sinθ * sinζ
    Bz = Bθ * cosθ

    return SVector{3, T}(Bx, By, Bz)
end

"""
    getB_tokamak_profile(x, y, z, q_profile, a, R₀, Bζ0) -> SVector{3}
    getB_tokamak_profile(r, q_profile, a, R₀, Bζ0) -> SVector{3}

Reconstruct the magnetic field distribution from a safety factor q-profile.
"""
@inline function getB_tokamak_profile(x, y, z, q_profile, a, R₀, Bζ0)
    return getB_tokamak_profile(SVector(x, y, z), q_profile, a, R₀, Bζ0)
end

@inline function getB_tokamak_profile(pos, q_profile, a, R₀, Bζ0)
    return TokamakProfile(q_profile, a, R₀, Bζ0)(pos)
end

