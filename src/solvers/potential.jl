function solve(
        solver::VectorPotential, sources::AbstractVector{<:AbstractCurrentSource}, r
    )
    isempty(sources) && return zero(SVector{3, Float64})
    acc = solve(solver, sources[1], r)
    for i in 2:length(sources)
        acc += solve(solver, sources[i], r)
    end
    return acc
end

