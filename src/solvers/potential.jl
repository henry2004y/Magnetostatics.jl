"""
    solve(solver::VectorPotential, field::AnalyticalMagnetosphere, r)

Compute vector potential A for a generalized magnetosphere model.
See [`AnalyticalMagnetosphere`](@ref) for details on the model parameters.
"""
function solve(::VectorPotential, f::AnalyticalMagnetosphere, r)
    @boundscheck length(r) >= 3 ||
        throw(ArgumentError("Input must have at least 3 elements."))
    FT = _promote_float(eltype(f.shielding_dipole_pos), r)
    @inbounds r_vec = SVector{3, FT}(r[1], r[2], r[3])
    dist_mp = r_vec[1] - f.mp_standoff + (r_vec[2]^2 + r_vec[3]^2) / (2 * f.mp_standoff)
    w_mp, _ = tanh_weight(dist_mp, f.mp_thickness)
    return w_mp * inner_potential(f, r_vec) +
        (1 - w_mp) * outer_potential(f, r_vec, dist_mp)
end

