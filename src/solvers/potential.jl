"""
    VectorPotential{BC <: AbstractBoundary} <: AbstractSolver

Solver that computes the magnetic vector potential `A`.
The default constructor `VectorPotential()` uses `OpenBoundary`.
"""
struct VectorPotential{BC <: AbstractBoundary} <: AbstractSolver
    bc::BC
end

VectorPotential() = VectorPotential(OpenBoundary())

"""
    solve(solver::VectorPotential, source::Wire, r) where T

Compute the vector potential A at position `r` generated by a `Wire` source.
Integral of (mu0 I / 4pi) * dl / |r - r'|.
"""
function solve(::VectorPotential, source::Wire{T}, r) where {T}
    @boundscheck length(r) >= 3 ||
        throw(ArgumentError("Input must have at least 3 elements."))
    FT = _promote_float(T, r)
    @inbounds r_vec = SVector{3, FT}(r[1], r[2], r[3])
    A = zero(SVector{3, FT})
    points = source.points
    I = source.current

    for i in 1:(length(points) - 1)
        r1 = points[i]
        r2 = points[i + 1]

        l = r2 - r1
        L = norm(l)
        L < 1.0e-20 && continue
        u = l / L

        d1_vec = r_vec - r1
        d2_vec = r_vec - r2
        d1 = sqrt(dot(d1_vec, d1_vec))
        d2 = sqrt(dot(d2_vec, d2_vec))

        val = log((d1 + d2 + L) / (d1 + d2 - L))

        A += (FT(μ0_4π) * I * val) * u
    end

    return A
end

"""
    solve(solver::VectorPotential, source::Dipole, r) where T

Compute vector potential A for a magnetic dipole.
A = (mu0 / 4pi) * (m x r) / r^3
"""
@inline solve(::VectorPotential, source::Dipole, r) = vector_potential(source, r)
@inline solve(::VectorPotential, field::LineDipole2D, r) = vector_potential(field, r)

@inline function _logcosh(x::T) where {T}
    ax = abs(x)
    ax < 10 && return log(cosh(x))
    return ax + log1p(exp(-2 * ax)) - log(T(2))
end

"""
    solve(solver::VectorPotential, field::HarrisSheet, r)

Compute vector potential A for a Harris current sheet.
A = (0, -B0 * L * log(cosh(z/L)), 0)
"""
function solve(::VectorPotential, field::HarrisSheet{T}, r) where {T}
    FT = _promote_float(T, r)
    z, L, B0 = FT(r[3]), field.L, field.B0
    return SVector{3, FT}(zero(FT), -B0 * L * _logcosh(z / L), zero(FT))
end

function solve(::VectorPotential, field::AsymmetricHarrisSheet{T}, r) where {T}
    FT = _promote_float(T, r)
    z = FT(r[3])
    (; B1, B2, L) = field
    ay = -((B1 + B2) / 2) * z - ((B1 - B2) / 2) * L * _logcosh(z / L)
    return SVector{3, FT}(zero(FT), ay, zero(FT))
end

function solve(::VectorPotential, field::ForceFreeHarrisSheet{T}, r) where {T}
    FT = _promote_float(T, r)
    z = FT(r[3])
    (; B0, L) = field
    ax = 2 * B0 * L * atan(tanh(z / (2 * L)))
    ay = -B0 * L * _logcosh(z / L)
    return SVector{3, FT}(ax, ay, zero(FT))
end

function solve(::VectorPotential, field::BifurcatedHarrisSheet{T}, r) where {T}
    FT = _promote_float(T, r)
    z = FT(r[3])
    (; B0, L, d) = field
    ay = -(B0 * L / 2) * (_logcosh((z - d) / L) + _logcosh((z + d) / L))
    return SVector{3, FT}(zero(FT), ay, zero(FT))
end

function solve(::VectorPotential, field::FadeevIsland{T}, r) where {T}
    FT = _promote_float(T, r)
    x, z = FT(r[1]), FT(r[3])
    (; B0, L, Lx, ε) = field
    u = z / L
    au = abs(u)
    lval = if au < 10
        log(cosh(u) + ε * cos(x / Lx))
    else
        au + log(FT(0.5) * (one(FT) + exp(-2 * au)) + exp(-au) * ε * cos(x / Lx))
    end
    return SVector{3, FT}(zero(FT), B0 * L * lval, zero(FT))
end

function solve(::VectorPotential, field::GuideFieldHarrisSheet{T}, r) where {T}
    FT = _promote_float(T, r)
    x, z = FT(r[1]), FT(r[3])
    (; B0, L, Bg, Bn) = field
    ay = -B0 * L * _logcosh(z / L) + Bn * x
    ax = Bg * z
    return SVector{3, FT}(ax, ay, zero(FT))
end

